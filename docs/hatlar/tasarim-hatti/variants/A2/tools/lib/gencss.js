// Generated CSS for the page stylesheet: the token variables tokens.css does not carry (tokenCss, before the page rules),
// the Röntgen token swap (.xray) and the reduced-motion preview (html.rm, a copy of every prefers-reduced-motion rule).
// Owner: F1a.
const { T, C, rd } = require('./inputs');
const { resolve } = require('./format');
const motion = require('./motion');
// Röntgen: every color token that is not a midnight-blue step (accent.1 to 12) and not paper (neutral.1 to 5, QR white)
// becomes a flat light gray, so only the measured ink remains. It is a value swap on the role tokens, like a theme.
function xrayCss() {
  const tok = rd('tokens.css').split('@media')[0];
  const accent = new Set(T.color.accent.map(s => s.hex.toUpperCase()));
  const paper = new Set(T.color.neutral.filter(s => s.step <= 5).map(s => s.hex.toUpperCase()).concat(['#FFFFFF']));
  const XR = { paper: resolve('neutral.3'), line: resolve('neutral.5'), ink: resolve('neutral.6') };
  const decl = [];
  for (const m of tok.matchAll(/--([\w-]+):\s*(#[0-9A-Fa-f]{6});/g)) {
    const hex = m[2].toUpperCase();
    if (accent.has(hex) || paper.has(hex)) continue;
    const o = C.hexToOklch(hex);
    decl.push('--' + m[1] + ': ' + (o.L >= 0.9 ? XR.paper : o.L >= 0.75 ? XR.line : XR.ink) + ';');
  }
  return '/* generated by tools/build.js: Röntgen token swap */\n.xray { ' + decl.join(' ') + ' --scrim-a: rgba(220, 222, 230, 0.55); --shadow-2: none; --shadow-3: none; }\n';
}
// Reduced-motion preview: every rule inside @media (prefers-reduced-motion: reduce) is copied under html.rm,
// so the switch reproduces the operating-system setting exactly (interact.js compares the two on every element).
function splitSel(s) { const out = []; let d = 0, cur = ''; for (const ch of s) { if (ch === '(') d++; if (ch === ')') d--; if (ch === ',' && !d) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out.map(x => x.trim()).filter(Boolean); }
function rmCss(css) {
  const src = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  const re = /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{/g; let m;
  while ((m = re.exec(src))) {
    let depth = 1, i = re.lastIndex;
    for (; i < src.length && depth; i++) { if (src[i] === '{') depth++; else if (src[i] === '}') depth--; }
    const inner = src.slice(re.lastIndex, i - 1);
    for (const r of inner.matchAll(/([^{}]+)\{([^{}]*)\}/g)) out.push(splitSel(r[1]).map(s => (s === ':root' ? 'html.rm' : 'html.rm ' + s)).join(', ') + ' {' + r[2] + '}');
  }
  if (!out.length) throw new Error('no reduced-motion rules found');
  return '/* generated by tools/build.js: Hareketi azalt önizlemesi (html.rm) */\n' + out.join('\n') + '\n';
}
// Component sizes as CSS variables (decisions-r2 E1): component.button.height.panel is --component-button-height-panel.
function componentVars() {
  const out = [];
  const walk = (obj, path, unit) => { for (const [k, v] of Object.entries(obj)) { if (typeof v === 'number') out.push('--' + path.concat(k).join('-') + ': ' + v + unit + ';'); else walk(v, path.concat(k), unit); } };
  for (const c of T.components) {
    if (c.size) walk(c.size, ['component', c.key], 'px');
    if (c.mark) walk(c.mark, ['component', c.key, 'mark'], 'px');
    if (c.number) walk(c.number, ['component', c.key], '');
  }
  return out;
}
// The tokens that tokens.css does not carry, written as CSS variables from tokens.json so the page never retypes them:
// the two font stacks, every type style of the panel and the phone (font shorthand and letter spacing), the two shadows, the scrim and the camera overlays, the timing constants, scale factors and distances, the focus ring
// geometry, line widths, the touch and click targets, component sizes, and the timing of every interaction pattern with its reduced-motion value
// (a value swap under prefers-reduced-motion, pattern by pattern; rmCss copies it under html.rm with the other rules).
function tokenCss() {
  const n12 = C.hexToRgb(resolve('neutral.12')).map(x => Math.round(x * 255)).join(', ');
  const root = ['--font-sans: ' + T.type.fallback + ';', '--font-mono: ' + T.type.monoFallback + ';'];
  // --type-<panel|phone>-<style>: the font shorthand; -ls: its letter spacing. The component demos read these.
  // -lh: the line height alone, for geometry that sits on a text line (the receipt node in the middle of its title line).
  for (const where of ['panel', 'phone']) for (const s of T.type[where]) root.push('--type-' + where + '-' + s.name + ': ' + s.weight + ' ' + s.size + 'px/' + s.line + 'px var(--font-' + (s.family === 'mono' ? 'mono' : 'sans') + ');', '--type-' + where + '-' + s.name + '-ls: ' + s.tracking + 'px;', '--type-' + where + '-' + s.name + '-lh: ' + s.line + 'px;');
  for (const e of T.shape.elevation) if (e.shadow !== 'none') root.push('--shadow-' + parseInt(e.name, 10) + ': ' + e.shadow.replace(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/g, (m, r, g, b, a) => 'rgba(' + [r, g, b].join(', ') + ', ' + a + ')') + ';');
  root.push('--scrim-a: rgba(' + n12 + ', ' + T.color.alpha.scrim + ');');
  const n1 = C.hexToRgb(resolve('neutral.1')).map(x => Math.round(x * 255)).join(', ');
  for (const k of ['cameraHover', 'cameraPressed']) if (T.color.alpha[k] !== undefined) root.push('--overlay-' + k + ': rgba(' + n1 + ', ' + T.color.alpha[k] + ');');
  for (const t of T.motion.timing) root.push('--time-' + t.name + ': ' + t.ms + 'ms;');
  for (const s of T.motion.scale) root.push('--scale-' + s.name + ': ' + s.value + ';');
  for (const s of T.motion.distance) root.push('--distance-' + s.name + ': ' + s.value + 'px;');
  for (const [k, v] of Object.entries(T.shape.focus)) root.push('--focus-' + k + ': ' + v + 'px;');
  for (const [k, l] of Object.entries(T.shape.line)) root.push('--line-' + k + ': ' + l.width + 'px;');
  for (const [k, v] of Object.entries(T.space.targets)) root.push('--target-' + k + ': ' + v + 'px;');
  root.push(...componentVars());
  const mv = motion.cssVars();
  root.push(...mv.root);
  return '/* generated by tools/build.js from tokens.json: type styles, shadows, scrim, timing, scale, distance, focus ring, lines, components, interaction patterns */\n:root { ' + root.join(' ') + ' }\n' +
    '@media (prefers-reduced-motion: reduce) { :root { ' + mv.reduced.join(' ') + ' } }\n';
}
module.exports = { xrayCss, rmCss, tokenCss, componentVars };
