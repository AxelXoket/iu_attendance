// Gate tests for the composition: tools/build.js with one module per section (tools/sections), the shared helpers
// (tools/lib, tools/screens) and the fragment hook. Every build runs in a throwaway copy of the variant (fixture.js),
// so the live page and report are never written. Run: node --test "tools/test/*.test.js" (or npm test in tools/)   Owner: F1a.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs'), path = require('path');
const { execFileSync } = require('child_process');
const { variantCopy } = require('./fixture');

const SECTIONS_DIR = path.join(__dirname, '..', 'sections');
const ids = fs.readdirSync(SECTIONS_DIR).filter(f => f.endsWith('.js')).map(f => f.slice(0, -3));
const mod = id => require(path.join(SECTIONS_DIR, id));
const titled = ids.filter(id => mod(id).title); // nav sections; ust (header) and footer have no title
const v = variantCopy();
test.after(() => v.remove());
const crlf = s => s.replace(/\r?\n/g, '\r\n');
// The default build of the copy (no fragments), made once and kept aside so any test can read it on its own.
let page = null;
function defaultBuild() {
  if (!page) {
    const r = v.run('build.js');
    assert.equal(r.code, 0, r.out);
    page = { html: v.read('tasarim.html'), report: JSON.parse(v.read('work/build-report.json')) };
  }
  return page;
}

test('without fragments: every section module is built once, in navigation order, under its own title', () => {
  const { html, report } = defaultBuild();
  const onPage = [...html.matchAll(/<section id="([^"]+)" class="sec">/g)].map(m => m[1]);
  const nav = report.nav;
  assert.deepEqual(onPage, nav.map(n => n.id), 'page order equals navigation order');
  assert.deepEqual([...onPage].sort(), [...titled].sort(), 'each titled module once, no other own section');
  for (const n of nav) {
    assert.equal(n.title, mod(n.id).title, n.id + ': navigation title comes from the module');
    assert.ok(html.includes('<section id="' + n.id + '" class="sec"><div class="sec-h"><p class="sec-no">' + n.no + '</p><div><h2>' + n.title + '</h2>'), n.id + ': numbered head');
  }
  assert.equal((html.match(/<header class="cover" id="ust">/g) || []).length, 1, 'header (ust) once');
  assert.equal((html.match(/<footer class="foot" id="kaynaklar">/g) || []).length, 1, 'footer once, carrying the Kaynaklar anchor');
});

test('the page embeds the merged stylesheet and script byte for byte, and no source marker', () => {
  const { html } = defaultBuild();
  const src = require(path.join(v.root, 'tools', 'lib', 'sources.js'));
  assert.ok(html.includes('\r\n' + crlf(src.pageCss()) + '\r\n/* generated by tools/build.js: Röntgen'), 'stylesheet');
  assert.ok(html.includes('<script>\r\n' + crlf(src.pageJs()) + '\r\n</script>'), 'page script');
  assert.equal(html.includes('@order'), false);
});

test('every icon the page draws, in its markup or from its script, has its symbol in the sprite', () => {
  const { html } = defaultBuild();
  const cut = html.indexOf('<script>window.QR_CODES');
  const markup = html.slice(0, cut), script = html.slice(cut);
  const symbols = new Set([...markup.matchAll(/<symbol id="([^"]+)"/g)].map(m => m[1]));
  const uses = [...new Set([...markup.matchAll(/<use href="#([^"]+)"/g)].map(m => m[1]))];
  assert.ok(uses.length > 50, 'control: the markup draws icons');
  assert.deepEqual(uses.filter(u => !symbols.has(u)), [], 'markup');
  // The page script draws 20 px icons by name: '#i20-x' literals, icon('x') and ptoast(text, 'x').
  const named = new Set([...script.matchAll(/#i20-([a-z_]+)"/g), ...script.matchAll(/\bicon\('([a-z_]+)'/g), ...script.matchAll(/ptoast\('(?:[^'\\]|\\.)*', '([a-z_]+)'/g)].map(m => 'i20-' + m[1]));
  assert.ok(named.size >= 4, 'control: the script draws icons by name');
  assert.deepEqual([...named].filter(u => !symbols.has(u)), [], 'script');
});

test('the sprite carries the icons the page script draws even when no section draws them', () => {
  const src = require(path.join(v.root, 'tools', 'lib', 'sources.js'));
  const js = src.pageJs();
  const named = new Set([...js.matchAll(/#i20-([a-z_]+)"/g), ...js.matchAll(/\bicon\('([a-z_]+)'/g), ...js.matchAll(/ptoast\('(?:[^'\\]|\\.)*', '([a-z_]+)'/g)].map(m => 'i20-' + m[1]));
  assert.ok(named.size >= 4, 'control: the script draws icons by name');
  const bare = execFileSync(process.execPath, ['-e', 'process.stdout.write(require(' + JSON.stringify(path.join(v.root, 'tools', 'lib', 'icons.js')) + ').sprite())'], { encoding: 'utf8', windowsHide: true });
  const symbols = new Set([...bare.matchAll(/<symbol id="([^"]+)"/g)].map(m => m[1]));
  assert.deepEqual([...named].filter(u => !symbols.has(u)), []);
});

test('a fragment replaces the own platform section; Kaynaklar is the footer line, not a numbered section', () => {
  const dir = v.fragDir({ 'platform.html': '<section id="platform"><h2>Platform deneme</h2><p>Bölüm {{no}}.</p></section>' });
  const out = path.join(v.tmp, 'platform.html');
  const r = v.run('build.js', ['--frag-dir', dir, '--out', out]);
  assert.equal(r.code, 0, r.out);
  const html = fs.readFileSync(out, 'utf8');
  assert.equal((html.match(/<section id="platform" class="sec frag">/g) || []).length, 1);
  assert.equal(html.includes('<section id="platform" class="sec">'), false, 'own platform section left out');
  assert.equal((html.match(/<section id="kaynaklar"/g) || []).length, 0, 'no numbered Kaynaklar section (G3 #21)');
  assert.equal(html.split('<footer class="foot" id="kaynaklar"><p class="foot-src"><b>Kaynaklar.</b>').length - 1, 1, 'the footer carries the sources line and the old anchor');
  assert.equal(JSON.parse(v.read('work/build-report.json')).nav.some(n => n.id === 'kaynaklar'), false, 'the navigation has no Kaynaklar item');
  const no = JSON.parse(v.read('work/build-report.json')).nav.find(n => n.id === 'platform').no;
  assert.ok(html.includes('<p>Bölüm ' + no + '.</p>'), '{{no}} becomes the navigation number');
});

test('a fragment with an en or em dash is left out and reported; the same fragment with a hyphen is used', () => {
  for (const [mark, used] of [['\u2013', false], ['\u2014', false], ['-', true]]) {
    const dir = v.fragDir({ 'ilkeler.html': '<section id="ilkeler"><h2>İlkeler</h2><p>a ' + mark + ' b</p></section>' });
    const out = path.join(v.tmp, 'dash.html');
    const r = v.run('build.js', ['--frag-dir', dir, '--out', out]);
    assert.equal(r.code, 0, r.out);
    const f = JSON.parse(v.read('work/build-report.json')).fragments.find(x => x.id === 'ilkeler');
    assert.equal(f.used, used, 'fragment with ' + JSON.stringify(mark));
    if (!used) assert.match(f.why, /U\+2013 ya da U\+2014/);
    assert.equal(/[\u2013\u2014]/.test(fs.readFileSync(out, 'utf8')), false);
  }
});

test('a dash that reaches the page from a section module stops the build', () => {
  const f = 'tools/sections/dogru.js', orig = v.read(f);
  const broken = orig.replace("dogru.title = 'Doğru ve yanlış';", "dogru.title = 'Doğru \u2013 yanlış';");
  assert.notEqual(broken, orig, 'control: the title line was found');
  v.write(f, broken);
  try {
    const r = v.run('build.js', ['--out', path.join(v.tmp, 'x.html')]);
    assert.notEqual(r.code, 0);
    assert.match(r.out, /dash found in output/);
  } finally { v.write(f, orig); }
  assert.equal(v.read(f), orig);
});

test('every section module builds on its own once the numbers are set, and not before', () => {
  const sectionJs = path.join(v.root, 'tools', 'lib', 'section.js');
  const early = (() => { try { execFileSync(process.execPath, ['-e', 'require(' + JSON.stringify(path.join(v.root, 'tools', 'sections', 'dogru.js')) + ')()'], { encoding: 'utf8', stdio: 'pipe', windowsHide: true }); return ''; } catch (e) { return String(e.stderr); } })();
  assert.match(early, /section numbers are not set/);
  const { setNav } = require(sectionJs);
  const vmod = id => require(path.join(v.root, 'tools', 'sections', id));
  setNav(Object.fromEntries(titled.map((id, i) => [id, String(i + 1).padStart(2, '0')])), Object.fromEntries(titled.map(id => [id, vmod(id).title])));
  for (const id of titled) {
    const h = vmod(id)();
    assert.ok(h.startsWith('<section id="' + id + '" class="sec"><div class="sec-h">') && h.endsWith('</section>'), id);
  }
  assert.ok(vmod('ust')().startsWith('<header class="cover" id="ust">'));
  assert.ok(vmod('footer')().startsWith('<footer class="foot" id="kaynaklar">'));
});
