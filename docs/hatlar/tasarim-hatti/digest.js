// Builds compact digests for builders from research/verify/lib files.
// Usage: node digest.js   writes digest.md (research with verification verdicts) and digest-lib.md (libraries with measured stats)
const fs = require('fs'), path = require('path');
const D = __dirname;
const read = f => JSON.parse(fs.readFileSync(f, 'utf8').replace(/^﻿/, ''));
const exists = f => fs.existsSync(f);
const VOID = exists(path.join(D, 'void.json')) ? read(path.join(D, 'void.json')) : {};
const lines = ['# Research digest (generated by digest.js)', '', 'Verdicts: doğrulandı = verified; kısmen = partly; desteklenmiyor = not supported (see note); eskimiş = outdated (see note); açılamadı = could not be opened. Treat desteklenmiyor and eskimiş findings as corrected by their note.', ''];
const counts = {};
for (const f of fs.readdirSync(path.join(D, 'research')).filter(f => /^R\d\d\.json$/.test(f)).sort()) {
  const id = f.slice(0, 3);
  const r = read(path.join(D, 'research', f));
  const v = exists(path.join(D, 'verify', f)) ? read(path.join(D, 'verify', f)) : { checked: [], recommendation_issues: [] };
  const vm = Object.fromEntries((v.checked || []).map(c => [c.finding, c]));
  counts[id] = { findings: r.findings.length, checked: (v.checked || []).length };
  lines.push(`## ${id} ${r.angle}`, '', r.summary, '');
  lines.push('### Recommendations');
  for (const k of r.recommendations || []) {
    if (VOID[k.id]) { lines.push(`- **${k.id} ${k.topic || ''}**: VOID BY OWNER LOCK, do not use: ${VOID[k.id]}`); continue; }
    lines.push(`- **${k.id} ${k.topic || ''}**: ${k.recommendation}${k.reasons ? ' Reasons: ' + k.reasons : ''} (based on ${(k.based_on || []).join(', ')})`);
    for (const val of k.values || []) lines.push(`  - ${val.name} = ${val.value}${val.note ? ' (' + val.note + ')' : ''}`);
    for (const a of k.alternatives || []) lines.push(`  - not: ${a.option}: ${a.why_not}`);
  }
  const issues = (v.recommendation_issues || []);
  if (issues.length) { lines.push('', '### Fact-checker issues with recommendations'); for (const i of issues) lines.push(`- ${i.recommendation}: ${i.issue}`); }
  lines.push('', '### Findings');
  for (const x of r.findings) {
    const c = vm[x.id];
    const tag = c ? ` [${c.verdict}${c.verdict !== 'doğrulandı' ? ': ' + c.note : ''}]` : (x.load_bearing ? ' [unchecked]' : '');
    lines.push(`- ${x.id}${x.load_bearing ? ' (load-bearing)' : ''} ${x.title}: ${x.claim} Evidence: ${x.evidence} Implication: ${x.implication} Source: ${x.sources.map(s => s.url).join(' ')}${tag}`);
  }
  if ((r.benchmarks || []).length) {
    lines.push('', '### Benchmarks');
    for (const b of r.benchmarks) lines.push(`- ${b.app} (${b.category}): palette ${b.palette}; radius ${b.radius}; type ${b.type}; motion ${b.motion}; nav ${b.navigation}; lessons ${b.lessons}`);
  }
  if ((r.signals || []).length) lines.push('', `(${r.signals.length} forum signals are summarized in the findings above.)`);
  if ((r.open_questions || []).length) { lines.push('', '### Open questions'); r.open_questions.forEach(q => lines.push('- ' + q)); }
  lines.push('');
}
fs.writeFileSync(path.join(D, 'digest.md'), lines.join('\n'));

const L = ['# Library digest (generated by digest.js; numbers measured by libstats.js)', ''];
const stats = exists(path.join(D, 'lib', 'stats.json')) ? read(path.join(D, 'lib', 'stats.json')) : {};
if (exists(path.join(D, 'lib', 'final.json'))) {
  const F = read(path.join(D, 'lib', 'final.json'));
  L.push('## FINAL STACK (adversarial critic verdict; this overrides the proposals below)', '');
  for (const side of ['phone', 'panel', 'shared']) {
    L.push(`### ${side}`);
    for (const e of F[side] || []) L.push(`- ${e.category}: **${e.pick}** ${e.version ? '(' + e.version + ')' : ''} ${e.why}${e.second ? ' Second: ' + e.second + '.' : ''}${e.risk ? ' Risk: ' + e.risk : ''}`);
    L.push('');
  }
  L.push('### Conflicts settled');
  for (const c of F.conflicts || []) L.push(`- ${c.topic}: ${c.decision} (${c.why})`);
  L.push('', '### Notes');
  for (const n of F.notes || []) L.push('- ' + n);
  L.push('', '## Original proposals (for reference)', '');
}
const libFiles = exists(path.join(D, 'lib')) ? fs.readdirSync(path.join(D, 'lib')).filter(f => /^L\d+\.json$/.test(f)).sort() : [];
for (const f of libFiles) {
  const j = read(path.join(D, 'lib', f));
  L.push(`## ${j.id} ${j.area}`, '', j.summary, '', 'Needs: ' + (j.needs || []).join(' | '), '');
  for (const c of j.candidates) {
    const s = stats[c.package] || {};
    const m = s.version ? ` [measured: v${s.version} on ${s.released}, ${s.weeklyDownloads ?? '?'} downloads/week, ${s.stars ?? '?'} stars, last push ${s.pushedAt || '?'}${s.pastYearAvgDaysToCloseIssue != null ? ', issues closed in ' + s.pastYearAvgDaysToCloseIssue + ' days on average' : ''}${s.archived ? ', ARCHIVED' : ''}${s.deprecated ? ', DEPRECATED' : ''}]` : ' [not measured]';
    L.push(`- ${c.id} ${c.category}: **${c.package}** (${c.verdict}) ${c.role} Why: ${c.why} Compat: ${c.compat} Modern: ${c.modern}${c.risks ? ' Risks: ' + c.risks : ''}${m}`);
  }
  L.push('', 'Stack: ' + (j.stack || []).map(s => `${s.category}: ${s.pick}${s.second ? ' (second ' + s.second + ')' : ''}`).join('; '), '');
}
fs.writeFileSync(path.join(D, 'digest-lib.md'), L.join('\n'));
const words = s => s.split(/\s+/).length;
console.log('digest.md', words(lines.join(' ')), 'words;', 'digest-lib.md', words(L.join(' ')), 'words;', JSON.stringify(counts));
